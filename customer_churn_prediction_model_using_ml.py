"""**4. Data Preprocessing**"""

df.head()

"""Label Encoding of Target Column"""

df["Churn"]= df["Churn"].replace({"Yes": 1, "No": 0})

df.head(3)

"""Label encoding of categorical features"""

# identifying columns with object data types
object_columns = df.select_dtypes(include = "object").columns

print(object_columns)

# initialise a dictionary to save the encoders
encoders= {}

# apply label encoding and store the encoders
for column in object_columns:
  label_encoder = LabelEncoder()
  df[column]= label_encoder.fit_transform(df[column])
  encoders[column]= label_encoder

# save the encoders to a pickle file
with open("encoders.pkl", "wb") as file:
  pickle.dump(encoders, file)

df.head(3)

"""**Training and Test data split**"""

# splitting the features and target
x= df.drop(columns=["Churn"])
y= df["Churn"]

print(x)

# split training and test data
x_train, x_test, y_train, y_test = train_test_split(x, y, test_size= 0.2, random_state= 42)

print(y_train.shape)

print(y_train.value_counts())

"""Synthetic Minority Oversampling Technique (SMOTE)"""

smote= SMOTE(random_state= 42)
x_train_smote, y_train_smote= smote.fit_resample(x_train, y_train)

print(y_train_smote.shape)

print(y_train_smote.value_counts())

"""**5. Model Training**

Training with dfault hyperparameters
"""

# dictionary of models
models = {"Decision Tree": DecisionTreeClassifier(random_state=42),
          "Random Forest": RandomForestClassifier(random_state=42),
          "XGBoost": XGBRFClassifier(random_state=42)
          }

# dictionary to store the cross validation results
cv_scores= {}

# perform 5-fold cross validation for each model
for model_name, model in models.items():
  print(f"Training {model_name} with default parameters")
  scores= cross_val_score(model, x_train_smote, y_train_smote, cv= 5, scoring= "accuracy")
  cv_scores[model_name]= scores
  print(f"{model_name} cross validation accuracy: {np.mean(scores):.2f}")
  print("-"*70)

cv_scores

"""Random Forest gives higher accuracy compared to other models for default parameters"""

rfc= RandomForestClassifier(random_state=42)
rfc.fit(x_train_smote, y_train_smote)

print(y_test.value_counts())

"""**6. Model Evaluation**"""

# evaluate on test data
y_test_pred = rfc.predict(x_test)
print("Accuracy Score: \n", accuracy_score(y_test, y_test_pred))
print("Confusion Matrix: \n", confusion_matrix(y_test, y_test_pred))
print("Classification Report: \n", classification_report(y_test, y_test_pred))

# save the trained model as a pickle file
model_data= {"model": rfc, "features_names": x.columns.to_list()}

with open("customer_churn_model.pkl", "wb") as file:
  pickle.dump(model_data, file)

